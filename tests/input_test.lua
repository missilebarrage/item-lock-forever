-- Toggling: the click combo through HandleModifiedItemClick, and the key binding.
local ITEMS = Harness.ITEMS

describe("Click", function()
	it("locks and unlocks with Alt+Left Click, with a chat line and a sound", function()
		local world, ns = Harness.Setup()
		local _, sword = world:Give(ITEMS.SWORD)
		world:ModifiedClick(sword, "LeftButton", { alt = true })
		expect(ns.Locks.IsLockedAt(sword)).toBe(true)
		expect(world:Output()).toContain("Locked |cffffffff|Hitem:2000::::::::|h[Sword]|h|r.")
		expect(world.sounds).toEqual({ 12189 })
		world:Advance(1)
		world:ModifiedClick(sword, "LeftButton", { alt = true })
		expect(ns.Locks.IsLockedAt(sword)).toBe(false)
		expect(world:Output()).toContain("Unlocked |cffffffff|Hitem:2000::::::::|h[Sword]|h|r.")
		expect(world.sounds).toEqual({ 12189, 8938 })
	end)

	it("plays the chosen lock and unlock sounds, or none", function()
		local world, ns = Harness.Setup()
		local _, sword = world:Give(ITEMS.SWORD)
		ns.Database.Set("lockSound", "chain")
		ns.Database.Set("unlockSound", "none")
		world.sounds = {}
		world:ModifiedClick(sword, "LeftButton", { alt = true })
		expect(world.sounds).toEqual({ 1212 })
		world:Advance(1)
		world:ModifiedClick(sword, "LeftButton", { alt = true })
		expect(world.sounds).toEqual({ 1212 })
		expect(ns.Locks.IsLockedAt(sword)).toBe(false)
		ns.Database.Set("lockSound", "none")
		world.sounds = {}
		world:Advance(1)
		world:ModifiedClick(sword, "LeftButton", { alt = true })
		expect(world.sounds).toEqual({})
		expect(ns.Locks.IsLockedAt(sword)).toBe(true)
	end)

	it("locks one stack, or every stack from an EllesmereUI combined stack", function()
		local world, ns = Harness.Setup()
		local _, linen = world:Give(ITEMS.LINEN, { count = 4 })
		local _, other = world:Give(ITEMS.LINEN, { count = 9 })
		world:ModifiedClick(linen, "LeftButton", { alt = true })
		expect(world:Output()).toContain("Locked this stack of")
		expect(ns.Locks.IsLockedAt(other)).toBe(false)
		-- EllesmereUI's All Items view shows both stacks as one button.
		local combined = Harness.Addons.NewEllesmereButton(world)
		Harness.Addons.PaintEllesmere(world, combined, 0, linen.slotIndex, 13)
		world:Advance(1)
		world:ModifiedClick(linen, "LeftButton", { alt = true }, combined)
		expect(world:Output()).toContain("Unlocked every stack of")
		expect(ns.Locks.IsLockedAt(linen)).toBe(false)
		world:Advance(1)
		world:ModifiedClick(linen, "LeftButton", { alt = true }, combined)
		expect(world:Output()).toContain("Locked every stack of")
		expect(ns.Locks.IsLockedAt(other)).toBe(true)
		-- Unlocking one stack in a normal view.
		world:Advance(1)
		world:ModifiedClick(other, "LeftButton", { alt = true })
		expect(world:Output()).toContain("Unlocked this stack of")
		expect(ns.Locks.IsLockedAt(linen)).toBe(true)
		expect(ns.Locks.IsLockedAt(other)).toBe(false)
	end)

	it("treats a one-stack EllesmereUI button as that stack", function()
		local world, ns = Harness.Setup()
		local _, linen = world:Give(ITEMS.LINEN, { count = 4 })
		local _, other = world:Give(ITEMS.LINEN, { count = 9 })
		local button = Harness.Addons.NewEllesmereButton(world)
		Harness.Addons.PaintEllesmere(world, button, 0, linen.slotIndex)
		world:ModifiedClick(linen, "LeftButton", { alt = true }, button)
		expect(ns.Locks.IsLockedAt(linen)).toBe(true)
		expect(ns.Locks.IsLockedAt(other)).toBe(false)
	end)

	it("needs exactly the chosen modifiers and button", function()
		local world, ns = Harness.Setup()
		local _, sword = world:Give(ITEMS.SWORD)
		world:ModifiedClick(sword, "LeftButton", { alt = true, shift = true })
		world:ModifiedClick(sword, "LeftButton", { alt = true, ctrl = true })
		world:ModifiedClick(sword, "RightButton", { alt = true })
		world:ModifiedClick(sword, "LeftButton", { ctrl = true })
		expect(ns.Locks.IsLockedAt(sword)).toBe(false)
		expect(world.printed).toEqual({})
	end)

	it("follows the chosen combo, and Off ignores clicks", function()
		local world, ns = Harness.Setup()
		local _, sword = world:Give(ITEMS.SWORD)
		local cases = {
			{ "ALT-RightButton", "RightButton", { alt = true } },
			{ "CTRL-ALT-RightButton", "RightButton", { alt = true, ctrl = true } },
			{ "CTRL-RightButton", "RightButton", { ctrl = true } },
		}
		for _, case in ipairs(cases) do
			ns.Database.Set("click", case[1])
			world:ModifiedClick(sword, "LeftButton", { alt = true })
			expect(ns.Locks.IsLockedAt(sword)).toBe(false)
			world:ModifiedClick(sword, case[2], case[3])
			expect(ns.Locks.IsLockedAt(sword)).toBe(true)
			world:Advance(1)
			world:ModifiedClick(sword, case[2], case[3])
			expect(ns.Locks.IsLockedAt(sword)).toBe(false)
			world:Advance(1)
		end
		ns.Database.Set("click", "NONE")
		world:ModifiedClick(sword, "LeftButton", { alt = true })
		expect(ns.Locks.IsLockedAt(sword)).toBe(false)
	end)

	it("works on bank items and worn items", function()
		local world, ns = Harness.Setup()
		world.bags[6].size = 28
		local _, banked = world:Give(ITEMS.SWORD, { bag = 6, slot = 3 })
		local _, worn = world:Equip(1, ITEMS.RING)
		world:ModifiedClick(banked, "LeftButton", { alt = true })
		world:ModifiedClick(worn, "LeftButton", { alt = true })
		expect(ns.Locks.IsLockedAt(banked)).toBe(true)
		expect(ns.Locks.IsLockedEquipped(1)).toBe(true)
	end)

	it("ignores clicks with an item on the cursor, while targeting a spell or at the Auction House", function()
		local world, ns = Harness.Setup({ auctionHouse = true })
		local _, sword = world:Give(ITEMS.SWORD)
		local _, other = world:Give(ITEMS.RING)
		world:PickUp(other)
		world:ModifiedClick(sword, "LeftButton", { alt = true })
		world.env.ClearCursor()
		world.spellTargeting = true
		world:ModifiedClick(sword, "LeftButton", { alt = true })
		world.spellTargeting = false
		world.env.AuctionHouseFrame:Show()
		world:ModifiedClick(sword, "LeftButton", { alt = true })
		expect(ns.Locks.IsLockedAt(sword)).toBe(false)
		world.env.AuctionHouseFrame:Hide()
		world:ModifiedClick(sword, "LeftButton", { alt = true })
		expect(ns.Locks.IsLockedAt(sword)).toBe(true)
	end)

	it("ignores empty slots, links without a location and slots that aren't yours", function()
		local world = Harness.Setup()
		world:ModifiedClick(Harness.Inventory.BagLocation(0, 12), "LeftButton", { alt = true })
		world.modifiers, world.mouseButton = { alt = true }, "LeftButton"
		world.env.HandleModifiedItemClick("|Hitem:2000|h[Sword]|h", nil)
		-- Buyback slots are inventory slots past the worn ones.
		local _, buyback = world:Equip(74, ITEMS.SWORD)
		world.env.HandleModifiedItemClick("|Hitem:2000|h[Sword]|h", buyback)
		expect(world.env.ItemLockForeverDB.items).toEqual({})
		expect(#world.errors).toBe(0)
	end)

	it("toggles once when one gesture reaches the click function twice", function()
		local world, ns = Harness.Setup()
		local _, sword = world:Give(ITEMS.SWORD)
		world:ModifiedClick(sword, "LeftButton", { alt = true })
		world:Advance(0.1)
		world:ModifiedClick(sword, "LeftButton", { alt = true })
		expect(ns.Locks.IsLockedAt(sword)).toBe(true)
		world:Advance(0.3)
		world:ModifiedClick(sword, "LeftButton", { alt = true })
		expect(ns.Locks.IsLockedAt(sword)).toBe(false)
	end)

	it("keeps Blizzard's own result and hooks the click function once", function()
		local world = Harness.Setup()
		local _, sword = world:Give(ITEMS.SWORD)
		world.modifiers, world.mouseButton = { alt = true }, "LeftButton"
		expect(world.env.HandleModifiedItemClick(world:Link(world:ItemAt(sword)), sword)).toBe(false)
		local hooked = 0
		for _, hook in ipairs(world.hooks) do
			if hook.name == "HandleModifiedItemClick" then
				hooked = hooked + 1
			end
		end
		expect(hooked).toBe(1)
	end)
end)

describe("Hold to unlock", function()
	local function Setup()
		local world, ns = Harness.Setup()
		ns.Database.Set("holdToUnlock", true)
		local _, swordAt = world:Give(ITEMS.SWORD)
		return world, ns, swordAt
	end

	-- A full click: press, hold for a while, release.
	local function Click(world, location, seconds)
		world:Hover(location)
		world:MouseDown("LeftButton", { alt = true })
		world:Advance(seconds)
		world:MouseUp("LeftButton")
		world:ModifiedClick(location, "LeftButton", { alt = true })
	end

	it("locks with a quick click, and unlocks only when the click is held for a second", function()
		local world, ns, swordAt = Setup()
		Click(world, swordAt, 0.1)
		expect(ns.Locks.IsLockedAt(swordAt)).toBe(true)
		world:Advance(1)
		Click(world, swordAt, 0.5)
		expect(ns.Locks.IsLockedAt(swordAt)).toBe(true)
		expect(world.uiMessages).toEqual({ "Hold Alt+Click to unlock" })
		world:Advance(1)
		Click(world, swordAt, 1.1)
		expect(ns.Locks.IsLockedAt(swordAt)).toBe(false)
		expect(world:Output()).toContain("Unlocked")
		expect(#world.uiMessages).toBe(1)
	end)

	it("doesn't unlock when you let go of Alt or move to another item before the second is up", function()
		local world, ns, swordAt = Setup()
		local _, ringAt = world:Give(ITEMS.RING)
		ns.Locks.Toggle(swordAt)
		ns.Locks.Toggle(ringAt)
		world:Hover(swordAt)
		world:MouseDown("LeftButton", { alt = true })
		world:Advance(0.5)
		world.modifiers = {}
		world:Advance(1)
		expect(ns.Locks.IsLockedAt(swordAt)).toBe(true)
		world:MouseUp("LeftButton")
		world:Hover(swordAt)
		world:MouseDown("LeftButton", { alt = true })
		world:Advance(0.5)
		world:Hover(ringAt)
		world:Advance(1)
		expect(ns.Locks.IsLockedAt(swordAt)).toBe(true)
		expect(ns.Locks.IsLockedAt(ringAt)).toBe(true)
	end)

	it("needs the chosen combo and the item under the mouse to be locked", function()
		local world, ns, swordAt = Setup()
		local _, ringAt = world:Give(ITEMS.RING)
		ns.Locks.Toggle(swordAt)
		world:Hover(swordAt)
		world:MouseDown("RightButton", { alt = true })
		world:Advance(1.5)
		world:MouseUp("RightButton")
		world:MouseDown("LeftButton", { ctrl = true })
		world:Advance(1.5)
		world:MouseUp("LeftButton")
		expect(ns.Locks.IsLockedAt(swordAt)).toBe(true)
		-- Holding on an unlocked item does nothing; its click locks it.
		Click(world, ringAt, 1.5)
		expect(ns.Locks.IsLockedAt(ringAt)).toBe(true)
	end)

	it("shows a swipe over the item while the hold runs", function()
		local world, ns, swordAt = Setup()
		ns.Locks.Toggle(swordAt)
		local button = world:ShowBag(0)[1]
		world:Hover(swordAt, button)
		world:MouseDown("LeftButton", { alt = true })
		local swipe
		for _, child in ipairs(world.env.UIParent.children or {}) do
			if child.objectType == "Cooldown" then
				swipe = child
			end
		end
		expect(swipe.shown).toBe(true)
		expect(swipe.points).toEqual({ { "ALL", button } })
		expect(swipe.cooldown.duration).toBe(1)
		world:Advance(0.3)
		world:MouseUp("LeftButton")
		expect(swipe.shown).toBe(false)
		expect(swipe.cooldown).toBeNil()
		expect(Harness.ForeignKeys(button)).toEqual({})
	end)

	it("works with the key binding: a quick press locks, holding the key unlocks", function()
		local world, ns, swordAt = Setup()
		world:Hover(swordAt)
		world.env.ItemLockForever_ToggleHovered("down")
		world.env.ItemLockForever_ToggleHovered("up")
		expect(ns.Locks.IsLockedAt(swordAt)).toBe(true)
		world:Advance(1)
		world.env.ItemLockForever_ToggleHovered("down")
		world:Advance(0.5)
		world.env.ItemLockForever_ToggleHovered("up")
		world:Advance(1)
		expect(ns.Locks.IsLockedAt(swordAt)).toBe(true)
		world.env.ItemLockForever_ToggleHovered("down")
		world:Advance(1.1)
		expect(ns.Locks.IsLockedAt(swordAt)).toBe(false)
		world.env.ItemLockForever_ToggleHovered("up")
		expect(ns.Locks.IsLockedAt(swordAt)).toBe(false)
	end)
end)

describe("Key binding", function()
	it("toggles the item whose tooltip is showing, on the key press only", function()
		local world, ns = Harness.Setup()
		local _, sword = world:Give(ITEMS.SWORD)
		world:Hover(sword)
		world.env.ItemLockForever_ToggleHovered("down")
		world.env.ItemLockForever_ToggleHovered("up")
		expect(ns.Locks.IsLockedAt(sword)).toBe(true)
		world:Advance(1)
		world.env.ItemLockForever_ToggleHovered("down")
		expect(ns.Locks.IsLockedAt(sword)).toBe(false)
	end)

	it("finds the item from the tooltip's slot when the data has no GUID", function()
		local world, ns = Harness.Setup({ behavior = { tooltipGUID = false } })
		local _, worn = world:Equip(5, ITEMS.RING)
		world.bags[6].size = 10
		local _, banked = world:Give(ITEMS.LINEN, { bag = 6, slot = 2 })
		world:Hover(worn)
		world.env.ItemLockForever_ToggleHovered()
		world:Hover(banked)
		world.env.ItemLockForever_ToggleHovered()
		expect(ns.Locks.IsLockedEquipped(5)).toBe(true)
		expect(ns.Locks.IsLockedAt(banked)).toBe(true)
	end)

	it("works whatever the click setting is, and does nothing without a tooltip", function()
		local world, ns = Harness.Setup()
		ns.Database.Set("click", "NONE")
		local _, sword = world:Give(ITEMS.SWORD)
		world.env.ItemLockForever_ToggleHovered()
		world:Hover(sword)
		world:HideTooltip()
		world.env.ItemLockForever_ToggleHovered()
		expect(ns.Locks.IsLockedAt(sword)).toBe(false)
		world:Hover(sword)
		world.env.ItemLockForever_ToggleHovered()
		expect(ns.Locks.IsLockedAt(sword)).toBe(true)
	end)
end)
