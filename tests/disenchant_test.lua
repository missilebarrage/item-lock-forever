-- Disenchant protection: locked items are held while Disenchant waits for its target.
local ITEMS = Harness.ITEMS
local DISENCHANT = 13262
local ENCHANT_BRACER = 7779

local function Lock(world, ns, location, view)
	expect(ns.Locks.Toggle(location, view)).toBe(true)
	return world:ItemAt(location)
end

describe("Disenchant", function()
	it("holds locked items as soon as Disenchant waits for a target, so they can't be picked", function()
		local world, ns = Harness.Setup()
		local _, swordAt = world:Give(ITEMS.SWORD)
		local _, linenAt = world:Give(ITEMS.LINEN, { count = 6 })
		local ring = world:Give(ITEMS.RING)
		local sword = Lock(world, ns, swordAt)
		local linen = Lock(world, ns, linenAt)
		-- A macro casts and picks the item at once: the hold is already there.
		world:StartTargeting(DISENCHANT)
		world:TargetItem(swordAt)
		expect(world.refusedTargets).toBe(1)
		expect(world.spellTargeting).toBe(true)
		expect(world.holds[sword.guid]).toBe("addon")
		expect(world.holds[linen.guid]).toBe("addon")
		expect(world.holds[ring.guid]).toBeNil()
		world:CancelTargeting()
		world:Advance(5)
		expect(world:Has(sword.guid)).toBe(true)
		expect(world.holds[sword.guid]).toBeNil()
		expect(world.holds[linen.guid]).toBeNil()
		expect(world.violations).toEqual({})
	end)

	it("lets unlocked items be disenchanted and releases the holds when the cast starts", function()
		local world, ns = Harness.Setup()
		local _, swordAt = world:Give(ITEMS.SWORD)
		local ring, ringAt = world:Give(ITEMS.RING)
		local sword = Lock(world, ns, swordAt)
		world:StartTargeting(DISENCHANT)
		world:TargetItem(ringAt)
		expect(world.holds[sword.guid]).toBeNil()
		world:Advance(5)
		expect(world:Has(ring.guid)).toBe(false)
		expect(world:Has(sword.guid)).toBe(true)
	end)

	it("leaves other spells that target items alone", function()
		local world, ns = Harness.Setup()
		local _, swordAt = world:Give(ITEMS.SWORD)
		local sword = Lock(world, ns, swordAt)
		world:StartTargeting(ENCHANT_BRACER)
		expect(world.calls.LockItem).toBe(0)
		world:TargetItem(swordAt)
		world:Advance(5)
		expect(world:Has(sword.guid)).toBe(true)
		expect(world.refusedTargets).toBeNil()
	end)

	it("keeps the vendor's holds when Disenchant stops waiting at a vendor", function()
		local world, ns = Harness.Setup()
		local _, swordAt = world:Give(ITEMS.SWORD)
		local sword = Lock(world, ns, swordAt)
		world:OpenMerchant()
		world:StartTargeting(DISENCHANT)
		world:CancelTargeting()
		expect(world.holds[sword.guid]).toBe("addon")
		expect(world.calls.LockItem).toBe(1)
		world:StartTargeting(DISENCHANT)
		world:CloseMerchant()
		expect(world.holds[sword.guid]).toBe("addon")
		world:CancelTargeting()
		expect(world.holds[sword.guid]).toBeNil()
	end)

	it("holds or releases at once when you lock or unlock with the key binding while targeting", function()
		local world, ns = Harness.Setup()
		local ring, ringAt = world:Give(ITEMS.RING)
		world:StartTargeting(DISENCHANT)
		world:Hover(ringAt)
		world.env.ItemLockForever_ToggleHovered()
		expect(ns.Locks.IsLockedAt(ringAt)).toBe(true)
		expect(world.holds[ring.guid]).toBe("addon")
		world:Advance(1)
		world.env.ItemLockForever_ToggleHovered()
		expect(world.holds[ring.guid]).toBeNil()
		world:TargetItem(ringAt)
		world:Advance(5)
		expect(world:Has(ring.guid)).toBe(false)
	end)

	it("holds locked items that arrive while Disenchant waits", function()
		local world, ns = Harness.Setup()
		local _, linenAt = world:Give(ITEMS.LINEN, { count = 2 })
		Lock(world, ns, linenAt, "all")
		world:StartTargeting(DISENCHANT)
		local looted = world:Give(ITEMS.LINEN, { count = 5 })
		world:Fire("BAG_UPDATE_DELAYED")
		expect(world.holds[looted.guid]).toBe("addon")
	end)
end)
