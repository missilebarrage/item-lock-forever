-- Vendor protection: holding locked items while a vendor is open, and buying back whatever still
-- gets sold.
local ITEMS = Harness.ITEMS
local PELT = 3002 -- an unlocked grey item

local function Lock(world, ns, location, view)
	expect(ns.Locks.Toggle(location, view)).toBe(true)
	return world:ItemAt(location)
end

local function Held(world, item)
	return world.holds[item.guid]
end

describe("Vendor hold", function()
	it("holds locked items while a vendor is open, so they can't be sold", function()
		local world, ns = Harness.Setup()
		local _, swordAt = world:Give(ITEMS.SWORD)
		local _, linenAt = world:Give(ITEMS.LINEN, { count = 12 })
		local ringItem, ringAt = world:Give(ITEMS.RING)
		local sword = Lock(world, ns, swordAt)
		local linen = Lock(world, ns, linenAt)
		world:OpenMerchant()
		expect(Held(world, sword)).toBe("addon")
		expect(Held(world, linen)).toBe("addon")
		expect(Held(world, ringItem)).toBeNil()
		world:RightClick(swordAt)
		expect(world:DragToMerchant(linenAt)).toBe(false)
		world:RightClick(ringAt)
		world:Advance(3)
		expect(world:Has(sword.guid)).toBe(true)
		expect(world:Count(ITEMS.LINEN)).toBe(12)
		expect(world:Has(ringItem.guid)).toBe(false)
		expect(world.calls.BuybackItem).toBe(0)
		world:CloseMerchant(true)
		expect(Held(world, sword)).toBeNil()
		expect(Held(world, linen)).toBeNil()
		expect(world.calls.UnlockItem).toBe(2)
		expect(world.violations).toEqual({})
	end)

	it("holds on whichever opening event comes first, once", function()
		for _, order in ipairs({ "interactionFirst", "showFirst", "showOnly" }) do
			local world, ns = Harness.Setup()
			local _, swordAt = world:Give(ITEMS.SWORD)
			Lock(world, ns, swordAt)
			world:OpenMerchant(order)
			expect(world.calls.LockItem).toBe(1)
			expect(ns.Merchant.IsOpen()).toBe(true)
			world:CloseMerchant()
			expect(ns.Merchant.IsOpen()).toBe(false)
		end
	end)

	it("leaves items the game holds alone and never releases them", function()
		local world, ns = Harness.Setup()
		local _, swordAt = world:Give(ITEMS.SWORD)
		local sword = Lock(world, ns, swordAt)
		world:PickUp(swordAt)
		world:OpenMerchant()
		expect(world.calls.LockItem).toBe(0)
		world:CloseMerchant()
		expect(Held(world, sword)).toBe("game")
		expect(world.calls.UnlockItem).toBe(0)
	end)

	it("holds or releases at once when you lock or unlock at the vendor", function()
		local world, ns = Harness.Setup()
		local ring, ringAt = world:Give(ITEMS.RING)
		local first, firstAt = world:Give(ITEMS.LINEN, { count = 5 })
		local second = world:Give(ITEMS.LINEN, { count = 9 })
		world:OpenMerchant()
		world:ModifiedClick(ringAt, "LeftButton", { alt = true })
		world:ModifiedClick(firstAt, "LeftButton", { alt = true })
		expect(Held(world, ring)).toBe("addon")
		expect(Held(world, first)).toBe("addon")
		expect(Held(world, second)).toBeNil()
		world:Advance(1)
		world:ModifiedClick(ringAt, "LeftButton", { alt = true })
		world:ModifiedClick(firstAt, "LeftButton", { alt = true })
		expect(Held(world, ring)).toBeNil()
		expect(Held(world, first)).toBeNil()
		-- Every stack: all of them are held, and all released together.
		ns.Locks.Toggle(firstAt, "all")
		expect(Held(world, first)).toBe("addon")
		expect(Held(world, second)).toBe("addon")
		ns.Locks.Toggle(firstAt, "all")
		expect(Held(world, first)).toBeNil()
		expect(Held(world, second)).toBeNil()
		world:RightClick(ringAt)
		world:Advance(1)
		expect(world:Has(ring.guid)).toBe(false)
	end)

	it("holds locked items that arrive while the vendor is open", function()
		local world, ns = Harness.Setup()
		local _, linenAt = world:Give(ITEMS.LINEN, { count = 3 })
		Lock(world, ns, linenAt, "all")
		world:OpenMerchant()
		local looted = world:Give(ITEMS.LINEN, { count = 4 })
		world:Fire("BAG_UPDATE_DELAYED")
		expect(Held(world, looted)).toBe("addon")
	end)

	it("stops an auto-seller that skips held items when the interaction event comes first", function()
		local world, ns = Harness.Setup({ autoSeller = "useContainer" })
		world:DefineItem(PELT, { name = "Ruined Pelt", maxStack = 5, quality = 0, sellPrice = 20 })
		local _, junkAt = world:Give(ITEMS.JUNK, { count = 6 })
		local _, rustyAt = world:Give(ITEMS.RUSTY)
		local pelt = world:Give(PELT, { count = 2 })
		local junk = Lock(world, ns, junkAt)
		local rusty = Lock(world, ns, rustyAt)
		world:OpenMerchant("interactionFirst")
		world:Advance(5)
		expect(world:Has(junk.guid)).toBe(true)
		expect(world:Has(rusty.guid)).toBe(true)
		expect(world:Has(pelt.guid)).toBe(false)
		expect(world.calls.BuybackItem).toBe(0)
	end)
end)

describe("Vendor backstop", function()
	it("buys back locked items an earlier auto-seller sold, one at a time", function()
		local world, ns = Harness.Setup({ autoSeller = "useContainer" })
		local _, junkAt = world:Give(ITEMS.JUNK, { count = 6 })
		local _, rustyAt = world:Give(ITEMS.RUSTY)
		local junk = Lock(world, ns, junkAt)
		local rusty = Lock(world, ns, rustyAt)
		local money = world.money
		world:OpenMerchant("showOnly")
		world:Advance(0.2)
		expect(world:Has(junk.guid)).toBe(false)
		expect(world:Has(rusty.guid)).toBe(false)
		world:Advance(5)
		expect(world:Has(junk.guid)).toBe(true)
		expect(world:Has(rusty.guid)).toBe(true)
		expect(world.calls.BuybackItem).toBe(2)
		expect(#world.buyback).toBe(0)
		expect(world.money).toBe(money)
		expect(ns.Locks.IsGUIDLocked(rusty.guid)).toBe(true)
		expect(Held(world, rusty)).toBe("addon")
		expect(Held(world, junk)).toBe("addon")
		local _, count = world:Output():gsub("was bought back", "")
		expect(count).toBe(2)
	end)

	it("restores locked items Sell All Junk sold, and nothing else", function()
		local world, ns = Harness.Setup({ autoSeller = "sellAllJunk" })
		world:DefineItem(PELT, { name = "Ruined Pelt", maxStack = 5, quality = 0, sellPrice = 20 })
		local _, junkAt = world:Give(ITEMS.JUNK, { count = 6 })
		local _, rustyAt = world:Give(ITEMS.RUSTY)
		local pelt = world:Give(PELT, { count = 2 })
		local junk = Lock(world, ns, junkAt)
		local rusty = Lock(world, ns, rustyAt)
		world:OpenMerchant()
		world:Advance(5)
		expect(world:Has(junk.guid)).toBe(true)
		expect(world:Has(rusty.guid)).toBe(true)
		expect(world:Has(pelt.guid)).toBe(false)
		expect(#world.buyback).toBe(1)
		expect(world.buyback[1].item.id).toBe(PELT)
	end)

	it("has nothing to do when the server's Sell All Junk honors holds", function()
		local world, ns = Harness.Setup({ autoSeller = "sellAllJunk", behavior = { junkHonorsHolds = true } })
		local _, rustyAt = world:Give(ITEMS.RUSTY)
		local rusty = Lock(world, ns, rustyAt)
		world:OpenMerchant()
		world:Advance(5)
		expect(world:Has(rusty.guid)).toBe(true)
		expect(world.calls.BuybackItem).toBe(0)
	end)

	it("restores items locked one by one sold before the vendor opened, but not every-stack locks", function()
		local world, ns = Harness.Setup()
		local _, swordAt = world:Give(ITEMS.SWORD)
		local _, linenAt = world:Give(ITEMS.LINEN, { count = 8 })
		local sword = Lock(world, ns, swordAt)
		local linen = Lock(world, ns, linenAt, "all")
		-- Sold earlier this session (e.g. at another vendor, before the lock or by an addon).
		world.bags[0][swordAt.slotIndex], world.bags[0][linenAt.slotIndex] = nil, nil
		world.buyback = { { item = linen, price = 104 }, { item = sword, price = 500 } }
		world:OpenMerchant()
		world:Advance(5)
		expect(world:Has(sword.guid)).toBe(true)
		expect(world:Has(linen.guid)).toBe(false)
		expect(world.calls.BuybackItem).toBe(1)
	end)

	it("only restores stacks sold while their type was locked", function()
		local world, ns = Harness.Setup()
		local _, soldAt = world:Give(ITEMS.LINEN, { count = 20 })
		local _, keptAt = world:Give(ITEMS.LINEN, { count = 5 })
		world:OpenMerchant()
		world:RightClick(soldAt)
		world:Advance(1)
		Lock(world, ns, keptAt, "all")
		world:Advance(5)
		expect(#world.buyback).toBe(1)
		expect(world.calls.BuybackItem).toBe(0)
		-- Still known at the next vendor this session.
		world:CloseMerchant()
		world:OpenMerchant()
		world:Advance(5)
		expect(world.calls.BuybackItem).toBe(0)
	end)

	it("never buys back an unlocked copy of locked gear", function()
		local world, ns = Harness.Setup()
		local _, lockedAt = world:Give(ITEMS.SWORD)
		local copy, copyAt = world:Give(ITEMS.SWORD)
		local locked = Lock(world, ns, lockedAt)
		world:OpenMerchant()
		world:RightClick(copyAt)
		world:Advance(5)
		expect(world:Has(copy.guid)).toBe(false)
		expect(world:Has(locked.guid)).toBe(true)
		expect(world.calls.BuybackItem).toBe(0)
	end)

	it("restores every locked item when the client sells held items", function()
		local world, ns = Harness.Setup({ behavior = { holdsBlockSales = false } })
		world.bags[1].size = 4
		local items = {}
		for index = 1, 3 do
			local _, at = world:Give(ITEMS.SWORD)
			items[index] = Lock(world, ns, at)
		end
		world:OpenMerchant()
		for slot = 1, 3 do
			world:RightClick(Harness.Inventory.BagLocation(0, slot))
		end
		world:Advance(10)
		for _, item in ipairs(items) do
			expect(world:Has(item.guid)).toBe(true)
			expect(Held(world, item)).toBe("addon")
		end
		expect(world.calls.BuybackItem).toBe(3)
		expect(#world.buyback).toBe(0)
	end)

	it("picks the right entry when the buyback list is full", function()
		local world, ns = Harness.Setup({ behavior = { holdsBlockSales = false } })
		world.bags[1].size = 16
		world:DefineItem(PELT, { name = "Ruined Pelt", maxStack = 5, quality = 0, sellPrice = 20 })
		for slot = 1, 12 do
			world:Give(PELT, { bag = 1, slot = slot })
		end
		local _, swordAt = world:Give(ITEMS.SWORD)
		local sword = Lock(world, ns, swordAt)
		world:OpenMerchant()
		for slot = 1, 12 do
			world:RightClick(Harness.Inventory.BagLocation(1, slot))
		end
		world:Advance(1)
		world:RightClick(swordAt)
		world:Advance(10)
		expect(world:Has(sword.guid)).toBe(true)
		expect(world.calls.BuybackItem).toBe(1)
		expect(#world.buyback).toBe(11)
		for _, entry in ipairs(world.buyback) do
			expect(entry.item.id).toBe(PELT)
		end
	end)

	it("gives up with a message when you can't afford it", function()
		local world, ns = Harness.Setup({ behavior = { holdsBlockSales = false } })
		local _, swordAt = world:Give(ITEMS.SWORD)
		local sword = Lock(world, ns, swordAt)
		world:OpenMerchant()
		world:RightClick(swordAt)
		world:Advance(0.1)
		world.money = 0
		world:Advance(5)
		expect(world.calls.BuybackItem).toBe(0)
		expect(world:Has(sword.guid)).toBe(false)
		expect(world:Output()).toContain("Couldn't buy back")
	end)

	it("tries twice when the bags are full, then says where the item is", function()
		local world, ns = Harness.Setup({ behavior = { holdsBlockSales = false } })
		local _, swordAt = world:Give(ITEMS.SWORD)
		local sword = Lock(world, ns, swordAt)
		world:OpenMerchant()
		world:RightClick(swordAt)
		world:Advance(0.1)
		for slot = 1, 16 do
			if not world.bags[0][slot] then
				world:Give(ITEMS.RING, { bag = 0, slot = slot })
			end
		end
		world:Advance(10)
		expect(world.calls.BuybackItem).toBe(2)
		expect(world:Has(sword.guid)).toBe(false)
		expect(world.uiErrors).toContain("Inventory is full.")
		local _, count = world:Output():gsub("Couldn't buy back", "")
		expect(count).toBe(1)
	end)

	it("does nothing once the vendor is closed", function()
		local world, ns = Harness.Setup({ behavior = { holdsBlockSales = false } })
		local _, swordAt = world:Give(ITEMS.SWORD)
		Lock(world, ns, swordAt)
		world:OpenMerchant()
		world:RightClick(swordAt)
		world:Advance(0.1)
		world:CloseMerchant()
		world:Advance(5)
		expect(world.calls.BuybackItem).toBe(0)
	end)

	it("buys back a locked worn item dragged onto the vendor", function()
		local world, ns = Harness.Setup()
		local _, wornAt = world:Equip(16, ITEMS.SWORD)
		local sword = Lock(world, ns, wornAt)
		world:OpenMerchant()
		expect(world:DragToMerchant(wornAt)).toBe(true)
		world:Advance(5)
		local back = world:Find(sword.guid)
		expect(back and back.bagID).toBe(0)
		expect(Held(world, sword)).toBe("addon")
	end)

	it("keeps the lock when a bought-back locked stack is stacked onto another one", function()
		local world, ns = Harness.Setup({ behavior = { holdsBlockSales = false, buybackMerges = true } })
		local _, lockedAt = world:Give(ITEMS.LINEN, { count = 5 })
		local _, otherAt = world:Give(ITEMS.LINEN, { count = 7 })
		Lock(world, ns, lockedAt)
		world:OpenMerchant()
		world:RightClick(lockedAt)
		world:Advance(5)
		expect(world:ItemAt(otherAt).count).toBe(12)
		expect(ns.Locks.IsLockedAt(otherAt)).toBe(true)
		expect(world:Output()).toContain("was bought back")
	end)

	it("never guesses when buyback entries carry no GUID", function()
		local world, ns = Harness.Setup({ behavior = { holdsBlockSales = false, buybackTooltipGUID = false } })
		local _, swordAt = world:Give(ITEMS.SWORD)
		local _, linenAt = world:Give(ITEMS.LINEN, { count = 2 })
		Lock(world, ns, swordAt)
		Lock(world, ns, linenAt)
		world:OpenMerchant()
		world:RightClick(swordAt)
		world:RightClick(linenAt)
		world:Advance(5)
		expect(world.calls.BuybackItem).toBe(0)
	end)

	it("explains its decisions with /ilf debug", function()
		local world, ns = Harness.Setup({ behavior = { holdsBlockSales = false } })
		local _, swordAt = world:Give(ITEMS.SWORD)
		Lock(world, ns, swordAt)
		world.env.SlashCmdList.ITEMLOCKFOREVER("debug")
		world:OpenMerchant()
		world:RightClick(swordAt)
		world:Advance(5)
		local output = world:Output()
		expect(output).toContain("hold: locked items 1 newly held 1")
		expect(output).toContain("buy back: entry 1 item 2000 try 1")
		expect(output).toContain("vendor open, buyback entries 0")
	end)
end)
