-- The lock model: gear and single stacks by exact item (GUID, every character), every stack of an
-- item by its ID (per character), and locks that follow items when stacks merge or split.
local ITEMS = Harness.ITEMS

describe("Locks", function()
	it("locks gear as that exact item: a second copy stays unlocked", function()
		local world, ns = Harness.Setup()
		local _, sword = world:Give(ITEMS.SWORD)
		local _, copy = world:Give(ITEMS.SWORD)
		expect(ns.Locks.Toggle(sword)).toBe(true)
		expect(ns.Locks.IsLockedAt(sword)).toBe(true)
		expect(ns.Locks.IsLockedAt(copy)).toBe(false)
		expect(ns.Locks.IsLockedInBag(copy.bagID, copy.slotIndex)).toBe(false)
		local saved = world.env.ItemLockForeverDB.items
		expect(saved[world:ItemAt(sword).guid]).toBe(ITEMS.SWORD)
	end)

	it("keeps a gear lock when the item moves to another slot", function()
		local world, ns = Harness.Setup()
		world.bags[1].size = 8
		local _, sword = world:Give(ITEMS.SWORD)
		ns.Locks.Toggle(sword)
		local moved = world:Move(sword, 1, 5)
		expect(ns.Locks.IsLockedInBag(1, 5)).toBe(true)
		expect(ns.Locks.IsLockedAt(moved)).toBe(true)
		expect(ns.Locks.IsLockedInBag(sword.bagID, sword.slotIndex)).toBe(false)
	end)

	it("locks every stack of a stackable item from a combined view, including new ones", function()
		local world, ns = Harness.Setup()
		local _, first = world:Give(ITEMS.LINEN, { count = 20 })
		local _, second = world:Give(ITEMS.LINEN, { count = 7 })
		local locked, kind = ns.Locks.Toggle(first, "all")
		expect(locked).toBe(true)
		expect(kind).toBe("all")
		expect(ns.Locks.IsLockedAt(second)).toBe(true)
		local _, looted = world:Give(ITEMS.LINEN, { count = 3 })
		expect(ns.Locks.IsLockedAt(looted)).toBe(true)
		expect(world.env.ItemLockForeverDB.items).toEqual({})
		expect(ns.Locks.Toggle(looted, "all")).toBe(false)
		expect(ns.Locks.IsLockedAt(first)).toBe(false)
	end)

	it("knows worn items", function()
		local world, ns = Harness.Setup()
		local _, worn = world:Equip(16, ITEMS.SWORD)
		expect(ns.Locks.IsLockedEquipped(16)).toBe(false)
		ns.Locks.Toggle(worn)
		expect(ns.Locks.IsLockedEquipped(16)).toBe(true)
		expect(ns.Locks.IsLockedEquipped(17)).toBe(false)
	end)

	it("keeps gear locks for every character and stack locks per character", function()
		local world, ns = Harness.Setup()
		local swordItem, sword = world:Give(ITEMS.SWORD)
		local _, linen = world:Give(ITEMS.LINEN, { count = 5 })
		ns.Locks.Toggle(sword)
		ns.Locks.Toggle(linen, "all")
		-- The same character after a reload.
		local again, againNs = Harness.Restart(world)
		local _, swordAgain = again:Give(ITEMS.SWORD, { guid = swordItem.guid })
		local _, linenAgain = again:Give(ITEMS.LINEN, { count = 5 })
		expect(againNs.Locks.IsLockedAt(swordAgain)).toBe(true)
		expect(againNs.Locks.IsLockedAt(linenAgain)).toBe(true)
		-- An alt: the sword was mailed over (same GUID); the alt's linen isn't locked.
		local alt, altNs = Harness.Restart(again, { player = { guid = "Player-1-0000BBBB" } })
		local _, mailed = alt:Give(ITEMS.SWORD, { guid = swordItem.guid })
		local _, altLinen = alt:Give(ITEMS.LINEN, { count = 5 })
		expect(altNs.Locks.IsLockedAt(mailed)).toBe(true)
		expect(altNs.Locks.IsLockedAt(altLinen)).toBe(false)
	end)

	it("counts gear locks per item ID as they come and go", function()
		local world, ns = Harness.Setup()
		local _, first = world:Give(ITEMS.SWORD)
		local _, second = world:Give(ITEMS.SWORD)
		ns.Locks.Toggle(first)
		ns.Locks.Toggle(second)
		expect(ns.Locks.MayBeLocked(ITEMS.SWORD)).toBe(true)
		ns.Locks.Toggle(first)
		expect(ns.Locks.MayBeLocked(ITEMS.SWORD)).toBe(true)
		ns.Locks.Toggle(second)
		expect(ns.Locks.MayBeLocked(ITEMS.SWORD)).toBe(false)
		expect(ns.Locks.MayBeLocked(nil)).toBe(false)
	end)

	it("signals every change", function()
		local world, ns = Harness.Setup()
		local seen = {}
		ns.Events.On("ILF_LOCKS_CHANGED", function(itemID, guid, locked)
			seen[#seen + 1] = { itemID, guid ~= nil, locked }
		end)
		local _, sword = world:Give(ITEMS.SWORD)
		local _, linen = world:Give(ITEMS.LINEN)
		ns.Locks.Toggle(sword)
		ns.Locks.Toggle(linen, "all")
		ns.Locks.Toggle(sword)
		expect(seen).toEqual({
			{ ITEMS.SWORD, true, true },
			{ ITEMS.LINEN, false, true },
			{ ITEMS.SWORD, true, false },
		})
	end)

	it("does nothing for an empty slot", function()
		local world, ns = Harness.Setup()
		expect(ns.Locks.Toggle(Harness.Inventory.BagLocation(0, 9))).toBeNil()
		expect(ns.Locks.IsLockedAt(Harness.Inventory.BagLocation(0, 9))).toBe(false)
		expect(ns.Locks.IsLockedInBag(0, 9)).toBe(false)
		expect(world.env.ItemLockForeverDB.items).toEqual({})
	end)
end)

describe("Single stacks", function()
	local function Stacks(world, ...)
		local locations = {}
		for index, count in ipairs({ ... }) do
			local _, location = world:Give(ITEMS.LINEN, { count = count })
			locations[index] = location
		end
		return unpack(locations)
	end

	it("locks one stack at a time", function()
		local world, ns = Harness.Setup()
		local first, second = Stacks(world, 20, 7)
		local locked, kind = ns.Locks.Toggle(first)
		expect(locked).toBe(true)
		expect(kind).toBe("stack")
		expect(ns.Locks.IsLockedAt(first)).toBe(true)
		expect(ns.Locks.IsLockedAt(second)).toBe(false)
		local _, looted = world:Give(ITEMS.LINEN, { count = 3 })
		expect(ns.Locks.IsLockedAt(looted)).toBe(false)
		expect(world.env.ItemLockForeverDB.items[world:ItemAt(first).guid]).toBe(ITEMS.LINEN)
		expect(ns.Locks.Toggle(first)).toBe(false)
		expect(world.env.ItemLockForeverDB.items).toEqual({})
	end)

	it("unlocks one stack of an item locked for every stack, and locks it again", function()
		local world, ns = Harness.Setup()
		local first, second = Stacks(world, 20, 7)
		ns.Locks.Toggle(first, "all")
		local locked, kind = ns.Locks.Toggle(second)
		expect(locked).toBe(false)
		expect(kind).toBe("stack")
		expect(ns.Locks.IsLockedAt(second)).toBe(false)
		expect(ns.Locks.IsLockedAt(first)).toBe(true)
		local _, looted = world:Give(ITEMS.LINEN, { count = 3 })
		expect(ns.Locks.IsLockedAt(looted)).toBe(true)
		expect(ns.Locks.Toggle(second)).toBe(true)
		expect(world.env.ItemLockForeverDB.free).toEqual({})
		expect(world.env.ItemLockForeverDB.items).toEqual({})
	end)

	it("from a combined view, unlocks every stack, single-stack locks included", function()
		local world, ns = Harness.Setup()
		local first, second = Stacks(world, 20, 7)
		ns.Locks.Toggle(first)
		ns.Locks.Toggle(second)
		expect(ns.Locks.IsLockedFor(first, "all")).toBe(true)
		expect(ns.Locks.Toggle(first, "all")).toBe(false)
		expect(ns.Locks.IsLockedAt(first)).toBe(false)
		expect(ns.Locks.IsLockedAt(second)).toBe(false)
		expect(world.env.ItemLockForeverDB.items).toEqual({})
		-- Locking every stack again leaves no stack unlocked on its own.
		ns.Locks.Toggle(first, "all")
		ns.Locks.Toggle(second)
		ns.Locks.Toggle(first, "all")
		ns.Locks.Toggle(first, "all")
		expect(ns.Locks.IsLockedAt(second)).toBe(true)
		expect(world.env.ItemLockForeverDB.free).toEqual({})
	end)

	it("locks the stack a locked stack is merged into", function()
		local world, ns = Harness.Setup()
		local first, second = Stacks(world, 5, 7)
		ns.Locks.Toggle(first)
		world:MergeStacks(first, second)
		expect(ns.Locks.IsLockedAt(second)).toBe(true)
	end)

	it("keeps both halves of a split locked stack locked", function()
		local world, ns = Harness.Setup()
		local first = Stacks(world, 10)
		ns.Locks.Toggle(first)
		local _, piece = world:SplitStack(first, 4, 0, 9)
		expect(ns.Locks.IsLockedAt(first)).toBe(true)
		expect(ns.Locks.IsLockedAt(piece)).toBe(true)
	end)

	it("locks nothing new when unlocked items join a locked stack or locked items are used up", function()
		local world, ns = Harness.Setup()
		local first, second, third = Stacks(world, 5, 3, 2)
		ns.Locks.Toggle(first)
		world:MergeStacks(second, first)
		expect(ns.Locks.IsLockedAt(first)).toBe(true)
		world:UseUp(first, 2)
		expect(ns.Locks.IsLockedAt(third)).toBe(false)
		expect(world.env.ItemLockForeverDB.items[world:ItemAt(third).guid]).toBeNil()
	end)

	it("locks a stack unlocked on its own again when locked items join it", function()
		local world, ns = Harness.Setup()
		local first, second = Stacks(world, 5, 7)
		ns.Locks.Toggle(first, "all")
		ns.Locks.Toggle(second)
		world:MergeStacks(first, second)
		expect(ns.Locks.IsLockedAt(second)).toBe(true)
		expect(world.env.ItemLockForeverDB.free).toEqual({})
	end)

	it("follows a locked stack into a bank stack", function()
		local world, ns = Harness.Setup()
		world.bags[6].size = 4
		local first = Stacks(world, 5)
		local _, banked = world:Give(ITEMS.LINEN, { bag = 6, slot = 2, count = 9 })
		ns.Locks.Toggle(first)
		world:MergeStacks(first, banked)
		expect(ns.Locks.IsLockedAt(banked)).toBe(true)
	end)

	it("keeps a single stack's lock on an alt it's mailed to, without locking the alt's other stacks", function()
		local world, ns = Harness.Setup()
		local first = Stacks(world, 5)
		local guid = world:ItemAt(first).guid
		ns.Locks.Toggle(first)
		local alt, altNs = Harness.Restart(world, { player = { guid = "Player-1-0000BBBB" } })
		local _, mailed = alt:Give(ITEMS.LINEN, { guid = guid, count = 5 })
		local _, own = alt:Give(ITEMS.LINEN, { count = 8 })
		expect(altNs.Locks.IsLockedAt(mailed)).toBe(true)
		expect(altNs.Locks.IsLockedAt(own)).toBe(false)
	end)
end)

describe("Review fixes", function()
	it("locks every copy of a non-stacking item from a combined button", function()
		local world, ns = Harness.Setup()
		local _, first = world:Give(ITEMS.RING)
		local _, second = world:Give(ITEMS.RING)
		ns.Locks.Toggle(second)
		expect(ns.Locks.IsLockedFor(first, "all")).toBe(true)
		local locked, kind = ns.Locks.Toggle(first, "all")
		expect(locked).toBe(false)
		expect(kind).toBe("all")
		expect(ns.Locks.IsLockedAt(second)).toBe(false)
		expect(ns.Locks.Toggle(first, "all")).toBe(true)
		expect(ns.Locks.IsLockedAt(first)).toBe(true)
		expect(ns.Locks.IsLockedAt(second)).toBe(true)
	end)

	it("drops the lock of a stack whose items all went into other stacks", function()
		local world, ns = Harness.Setup()
		local _, first = world:Give(ITEMS.LINEN, { count = 5 })
		local _, second = world:Give(ITEMS.LINEN, { count = 7 })
		local firstGUID = world:ItemAt(first).guid
		ns.Locks.Toggle(first)
		ns.Locks.Toggle(second)
		world:MergeStacks(first, second)
		expect(ns.Locks.IsLockedAt(second)).toBe(true)
		expect(world.env.ItemLockForeverDB.items[firstGUID]).toBeNil()
		-- One that was used up (or mailed) keeps its lock.
		local _, third = world:Give(ITEMS.LINEN, { count = 2 })
		local thirdGUID = world:ItemAt(third).guid
		ns.Locks.Toggle(third)
		world:UseUp(third, 2)
		expect(world.env.ItemLockForeverDB.items[thirdGUID]).toBe(ITEMS.LINEN)
	end)

	it("signals once per item when stacks get locked by a merge", function()
		local world, ns = Harness.Setup()
		local _, first = world:Give(ITEMS.LINEN, { count = 5 })
		local _, second = world:Give(ITEMS.LINEN, { count = 7 })
		ns.Locks.Toggle(first)
		local signals = 0
		ns.Events.On("ILF_LOCKS_CHANGED", function()
			signals = signals + 1
		end)
		world:MergeStacks(first, second)
		expect(signals).toBe(1)
	end)
end)
