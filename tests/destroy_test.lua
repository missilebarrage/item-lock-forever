-- Destroy protection: dropping a locked item outside the bags puts it back instead.
local ITEMS = Harness.ITEMS

describe("Destroy", function()
	it("puts a locked item back and closes the dialog without touching it", function()
		local world, ns = Harness.Setup()
		local _, swordAt = world:Give(ITEMS.SWORD)
		local sword = world:ItemAt(swordAt)
		ns.Locks.Toggle(swordAt)
		expect(world:DragToWorld(swordAt)).toBe(true)
		expect(world.cursor).toBeNil()
		expect(world.popup).toBeNil()
		expect(world:AcceptPopup()).toBe(false)
		expect(world:Has(sword.guid)).toBe(true)
		expect(world.holds[sword.guid]).toBeNil()
		expect(world.uiErrors).toEqual({
			"|cffffffff|Hitem:2000::::::::|h[Sword]|h|r is locked, so it can't be destroyed.",
		})
		expect(world.violations).toEqual({})
	end)

	it("protects the type-DELETE dialog's items and every stack of a locked type", function()
		local world, ns = Harness.Setup()
		local _, ringAt = world:Give(ITEMS.RING)
		local _, linenAt = world:Give(ITEMS.LINEN, { count = 3 })
		local _, otherAt = world:Give(ITEMS.LINEN, { count = 9 })
		ns.Locks.Toggle(ringAt)
		ns.Locks.Toggle(linenAt, "all")
		world:DragToWorld(ringAt)
		world:DragToWorld(otherAt)
		expect(world.popup).toBeNil()
		expect(world:Count(ITEMS.LINEN)).toBe(12)
		expect(world:ItemAt(ringAt)).toBeTruthy()
		expect(#world.uiErrors).toBe(2)
	end)

	it("finds the item from the cursor when the event has no GUID", function()
		local world, ns = Harness.Setup({ behavior = { deleteGUID = false } })
		local _, swordAt = world:Give(ITEMS.SWORD)
		ns.Locks.Toggle(swordAt)
		world:DragToWorld(swordAt)
		expect(world.popup).toBeNil()
		expect(world:ItemAt(swordAt)).toBeTruthy()
	end)

	it("leaves unlocked items to the game's dialog", function()
		local world = Harness.Setup()
		local sword, swordAt = world:Give(ITEMS.SWORD)
		world:DragToWorld(swordAt)
		expect(world.popup.which).toBe("DELETE_ITEM")
		expect(world.cursor).toBe(swordAt)
		expect(world:AcceptPopup()).toBe(true)
		expect(world:Has(sword.guid)).toBe(false)
		expect(world.uiErrors).toEqual({})
	end)
end)
